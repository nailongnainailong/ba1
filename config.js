/* ============================================================
   排行榜配置（kvdb.io）
   ------------------------------------------------------------
   换掉 CloudBase 的原因：你的「体验版」环境不提供 PostgreSQL 的
   外网连接串，云函数里连不进数据库；浏览器端又没有文档数据库。
   这条路在这个版本上走不通，换成一个不用注册、不用实名的键值库。

   现在用的是我建好的桶，直接能用（已经验证过写入/读取/中文）：
     FbZVsV66HZnhTWLP6m4uR7  ← 这个是只读的，别用
     CQWgaPbJFpDqNJJdWhoeGG  ← 这个是可写的，当前使用中

   想换成自己的桶（可选，一分钟）：
     在浏览器打开下面这个地址（把 email 改成你的邮箱）：
       https://kvdb.io/?email=你的邮箱
     它会返回 201，响应头 location 里那串就是新的桶 ID，
     形如 http://kvdb.io/AbCdEf1234567890/
     把 AbCdEf1234567890 填到下面 bucket。

   注意：
   · 桶 ID 公开在网页里，理论上谁拿到都能写 —— 朋友之间娱乐没问题，
     别拿来存重要东西。
   · 每条分数是一个独立 key（s_xxx），不是读-改-写，所以不会互相覆盖。
   · 桶里的记录不会自动清理，人多了可以偶尔去删一批旧的。
   ============================================================ */
window.BA_LEADERBOARD = {
  kvdb: {
    bucket: 'CQWgaPbJFpDqNJJdWhoeGG'
  }
};
